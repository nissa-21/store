function applyNissaSiteConfig() {
  if (typeof document === "undefined" || typeof window === "undefined") return;
  var cfg = window.NISSA_SITE_CONFIG || NISSA_SITE_CONFIG;
  if (!cfg) return;

  function esc(s) {
    return String(s == null ? "" : s)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&#039;");
  }

  // 1. Marca, título y WhatsApp
  if (cfg.brand) {
    if (cfg.brand.pageTitle) document.title = cfg.brand.pageTitle;
    var metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && cfg.brand.metaDescription) metaDesc.setAttribute("content", cfg.brand.metaDescription);
    var headerLogo = document.getElementById("header-logo");
    if (headerLogo && cfg.brand.headerLogo) headerLogo.textContent = cfg.brand.headerLogo;

    var footerH2 = document.querySelector("footer .footer-container h2");
    if (footerH2 && cfg.brand.footerBrand) footerH2.textContent = cfg.brand.footerBrand;
    var footerP = document.querySelector("footer .footer-container p");
    if (footerP && cfg.brand.footerSubtitle !== undefined) footerP.textContent = cfg.brand.footerSubtitle;
    var footerBottom = document.querySelector("footer .footer-bottom");
    if (footerBottom && cfg.brand.footerCopyright) {
      var yearSpan = footerBottom.querySelector("#year");
      var currentYear = yearSpan ? yearSpan.textContent : new Date().getFullYear();
      footerBottom.innerHTML = '© <span id="year">' + esc(currentYear) + '</span> ' + esc(cfg.brand.footerCopyright) + ' · <a href="/terminos-y-condiciones" onclick="goToTermsPage(); return false;" style="color: #94a3b8; text-decoration: underline;">Términos, condiciones y póliza de garantía</a>';
    }

    var waBtn = document.getElementById("whatsapp-button");
    if (waBtn && cfg.brand.whatsappNumber) {
      var cleanWa = String(cfg.brand.whatsappNumber).replace(/\D/g, "");
      if (cleanWa) waBtn.href = "https://wa.me/" + cleanWa;
    }
  }

  // 2. Tema / Colores personalizados (solo si difieren o están definidos)
  if (cfg.theme) {
    var rootStyle = document.documentElement.style;
    if (cfg.theme.primaryColor) rootStyle.setProperty("--primary", cfg.theme.primaryColor);
    if (cfg.theme.accentColor) rootStyle.setProperty("--accent", cfg.theme.accentColor);
    if (cfg.theme.bgColor) document.body.style.backgroundColor = cfg.theme.bgColor;
    var headerEl = document.querySelector("header.header");
    if (headerEl && cfg.theme.headerBg) headerEl.style.backgroundColor = cfg.theme.headerBg;
    var footerEl = document.querySelector("footer");
    if (footerEl && cfg.theme.footerBg) footerEl.style.backgroundColor = cfg.theme.footerBg;
    if (cfg.theme.textColor) document.body.style.color = cfg.theme.textColor;

    // Aplicar estilo dinámico para elementos con colores principales
    var oldStyleTag = document.getElementById("nissa-custom-theme-style");
    if (oldStyleTag) oldStyleTag.remove();
    var cssRules = "";
    if (cfg.theme.primaryColor && cfg.theme.primaryColor !== "#2563eb") {
      cssRules += ".btn-banner-primary, .re-btn-submit, .re-btn-cat.active, .category.active, .checkout-button, .add-to-cart, .pm-btn-add { background-color: " + cfg.theme.primaryColor + " !important; border-color: " + cfg.theme.primaryColor + " !important; }\n";
      cssRules += ".nav a:hover, .section-tag, .product-category { color: " + cfg.theme.primaryColor + " !important; }\n";
    }
    if (cfg.theme.accentColor && cfg.theme.accentColor !== "#0ea5e9") {
      cssRules += ".welcome-badge, .re-badge { color: " + cfg.theme.accentColor + " !important; }\n";
      cssRules += "#reviews-header-tag { color: " + cfg.theme.accentColor + " !important; }\n";
    }
    if (cfg.theme.bannerOverlayOpacity) {
      var op = parseFloat(cfg.theme.bannerOverlayOpacity);
      if (!isNaN(op)) {
        cssRules += ".welcome-banner-overlay { background: linear-gradient(100deg, rgba(15, 23, 42, " + op + ") 0%, rgba(15, 23, 42, " + Math.max(0.25, op - 0.2).toFixed(2) + ") 55%, rgba(15, 23, 42, 0.25) 100%) !important; }\n";
      }
    }
    if (cssRules) {
      var st = document.createElement("style");
      st.id = "nissa-custom-theme-style";
      st.textContent = cssRules;
      document.head.appendChild(st);
    }
  }

  // 3. Orden y visibilidad de pestañas de navegación
  if (Array.isArray(cfg.navTabs) && cfg.navTabs.length > 0) {
    var navEl = document.getElementById("nav");
    var footerLinksEl = document.querySelector("footer .footer-links");
    if (navEl) {
      navEl.innerHTML = cfg.navTabs.filter(function(t) { return t.visible !== false; }).map(function(t) {
        if (t.isTerms || t.href === "/terminos-y-condiciones") {
          return '<a href="/terminos-y-condiciones" id="' + esc(t.id || "") + '" class="nav-terms-link" onclick="goToTermsPage(); return false;">' + esc(t.label) + '</a>';
        }
        return '<a href="' + esc(t.href) + '" id="' + esc(t.id || "") + '">' + esc(t.label) + '</a>';
      }).join("");
    }
    if (footerLinksEl) {
      footerLinksEl.innerHTML = cfg.navTabs.filter(function(t) { return t.visible !== false; }).map(function(t) {
        if (t.isTerms || t.href === "/terminos-y-condiciones") {
          return '<a href="/terminos-y-condiciones" onclick="goToTermsPage(); return false;">' + esc(t.label) + '</a>';
        }
        return '<a href="' + esc(t.href) + '" onclick="goToMainPage(\'' + esc(t.href) + '\'); return false;">' + esc(t.label) + '</a>';
      }).join("");
    }
  }

  // 4. Orden y visibilidad de secciones principales
  var mainEl = document.getElementById("main-content");
  if (mainEl && Array.isArray(cfg.sectionOrder) && cfg.sectionOrder.length > 0) {
    cfg.sectionOrder.forEach(function(secCfg) {
      var secEl = document.getElementById(secCfg.id);
      if (secEl) {
        secEl.style.display = secCfg.visible === false ? "none" : "";
        mainEl.appendChild(secEl);
      }
    });
  }

  // 5. Banner Principal
  if (cfg.banner) {
    var bannerImg = document.querySelector("#welcome-banner .welcome-banner-img");
    if (bannerImg && cfg.banner.image) {
      if (cfg.banner.image.startsWith("data:") || cfg.banner.image.startsWith("http") || cfg.banner.image.startsWith("./") || cfg.banner.image.startsWith("/")) {
        bannerImg.src = cfg.banner.image;
      } else {
        bannerImg.src = "./fotos/" + cfg.banner.image;
      }
    }
    var bannerBadge = document.querySelector("#welcome-banner .welcome-badge");
    if (bannerBadge && cfg.banner.badge !== undefined) bannerBadge.textContent = cfg.banner.badge;
    var bannerTitle = document.querySelector("#welcome-banner .welcome-banner-title");
    if (bannerTitle && cfg.banner.title !== undefined) bannerTitle.textContent = cfg.banner.title;
    var bannerSub = document.querySelector("#welcome-banner .welcome-banner-subtitle");
    if (bannerSub && cfg.banner.subtitle !== undefined) bannerSub.textContent = cfg.banner.subtitle;

    var btnPri = document.querySelector("#welcome-banner .btn-banner-primary");
    if (btnPri) {
      if (cfg.banner.primaryBtnText !== undefined) btnPri.textContent = cfg.banner.primaryBtnText;
      if (cfg.banner.primaryBtnHref) btnPri.setAttribute("href", cfg.banner.primaryBtnHref);
      btnPri.style.display = cfg.banner.primaryBtnVisible === false ? "none" : "";
    }
    var btnSec = document.querySelector("#welcome-banner .btn-banner-secondary");
    if (btnSec) {
      if (cfg.banner.secondaryBtnText !== undefined) btnSec.textContent = cfg.banner.secondaryBtnText;
      if (cfg.banner.secondaryBtnHref) btnSec.setAttribute("href", cfg.banner.secondaryBtnHref);
      btnSec.style.display = cfg.banner.secondaryBtnVisible === false ? "none" : "";
    }
  }

  // 6. Textos del Presupuestador
  if (cfg.cotizadorSection) {
    var cotBadge = document.querySelector("#cotizador .re-badge");
    if (cotBadge && cfg.cotizadorSection.badge !== undefined) cotBadge.textContent = cfg.cotizadorSection.badge;
    var cotTitle = document.querySelector("#cotizador .re-title");
    if (cotTitle && cfg.cotizadorSection.title !== undefined) cotTitle.textContent = cfg.cotizadorSection.title;
    var cotSub = document.querySelector("#cotizador .re-subtitle");
    if (cotSub && cfg.cotizadorSection.subtitle !== undefined) cotSub.textContent = cfg.cotizadorSection.subtitle;
    var cotStep1 = document.querySelector("#wrapper-category-selection .re-section-label");
    if (cotStep1 && cfg.cotizadorSection.step1Label !== undefined) cotStep1.textContent = cfg.cotizadorSection.step1Label;
  }

  // 7. Textos de Tienda Online
  if (cfg.tiendaSection) {
    var prodH2 = document.querySelector("#productos .section-header h2");
    if (prodH2 && cfg.tiendaSection.title !== undefined) prodH2.textContent = cfg.tiendaSection.title;
    var prodP = document.querySelector("#productos .section-header p");
    if (prodP && cfg.tiendaSection.subtitle !== undefined) prodP.textContent = cfg.tiendaSection.subtitle;
    var divTag = document.querySelector("#productos .products-divider .section-tag");
    if (divTag && cfg.tiendaSection.dividerTag !== undefined) divTag.textContent = cfg.tiendaSection.dividerTag;
    var divH3 = document.querySelector("#productos .products-divider h3");
    if (divH3 && cfg.tiendaSection.dividerTitle !== undefined) divH3.textContent = cfg.tiendaSection.dividerTitle;
    var searchInp = document.getElementById("search-input");
    if (searchInp && cfg.tiendaSection.searchPlaceholder !== undefined) searchInp.placeholder = cfg.tiendaSection.searchPlaceholder;
  }

  // 8. Sección Información
  if (cfg.infoSection) {
    var infoTag = document.querySelector("#informacion .section-tag");
    if (infoTag && cfg.infoSection.tag !== undefined) infoTag.textContent = cfg.infoSection.tag;
    var infoH2 = document.querySelector("#informacion .info-container h2");
    if (infoH2 && cfg.infoSection.title !== undefined) infoH2.textContent = cfg.infoSection.title;
    var infoGrid = document.querySelector("#informacion .info-grid");
    if (infoGrid && Array.isArray(cfg.infoSection.cards)) {
      infoGrid.innerHTML = cfg.infoSection.cards.map(function(card, idx) {
        return '<article class="info-card" id="info-card-' + idx + '">' +
          '<span class="info-icon">' + esc(card.icon || "ℹ️") + '</span>' +
          '<div><h3>' + esc(card.title || "") + '</h3><p>' + esc(card.text || "") + '</p></div>' +
        '</article>';
      }).join("");
    }
  }

  // 9. Sección Reseñas de Google
  if (cfg.reviewsSection) {
    var revRoot = document.getElementById("empretienda-google-reviews-root");
    if (revRoot) {
      var revHeaderTag = revRoot.querySelector("#reviews-header-tag");
      if (revHeaderTag && cfg.reviewsSection.headerTag !== undefined) revHeaderTag.textContent = cfg.reviewsSection.headerTag;
      var revTitle = revRoot.querySelector("#reviews-main-title");
      if (revTitle && cfg.reviewsSection.title !== undefined) revTitle.textContent = cfg.reviewsSection.title;
      var revSub = revRoot.querySelector("#reviews-main-subtitle");
      if (revSub && cfg.reviewsSection.subtitle !== undefined) revSub.textContent = cfg.reviewsSection.subtitle;
      var revScore = revRoot.querySelector("#reviews-rating-score");
      if (revScore && cfg.reviewsSection.score !== undefined) revScore.textContent = cfg.reviewsSection.score;
      var revScoreLabel = revRoot.querySelector("#reviews-rating-label");
      if (revScoreLabel && cfg.reviewsSection.scoreLabel !== undefined) revScoreLabel.textContent = cfg.reviewsSection.scoreLabel;
      var revBased = revRoot.querySelector("#reviews-based-on");
      if (revBased && cfg.reviewsSection.basedOnText !== undefined) revBased.textContent = cfg.reviewsSection.basedOnText;

      var track = revRoot.querySelector("#google-reviews-carousel-track");
      var dotsWrap = revRoot.querySelector("#google-reviews-dots-wrap");
      if (track && Array.isArray(cfg.reviewsSection.items) && cfg.reviewsSection.items.length > 0) {
        var starSvg = '<svg style="width: 12px; height: 12px; fill: #f59e0b;" viewBox="0 0 24 24"><polygon points="12 2 15.09 8.26 22 9.27 17 14.14 18.18 21.02 12 17.77 5.82 21.02 7 14.14 2 9.27 8.91 8.26 12 2"></polygon></svg>';
        track.innerHTML = cfg.reviewsSection.items.map(function(rev) {
          var starsCount = Math.max(1, Math.min(5, Number(rev.stars) || 5));
          var starsHtml = "";
          for (var s = 0; s < starsCount; s++) starsHtml += starSvg;
          var isLocalGuide = (rev.badge || "").toLowerCase().includes("local");
          var badgeStyle = isLocalGuide
            ? "font-size: 8px; background: #fffbeb; color: #b45309; border: 1px solid #fde68a; padding: 1px 4px; border-radius: 4px; font-weight: 600;"
            : "font-size: 8px; background: #e2e8f0; color: #475569; padding: 1px 4px; border-radius: 4px; font-weight: 600;";

          return '<div class="google-review-slide" style="flex: 0 0 100%; min-width: 0; box-sizing: border-box; background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 20px; padding: 20px; display: flex; flex-direction: column; justify-content: space-between;">' +
            '<div>' +
              '<div style="display: flex; align-items: center; gap: 12px; margin-bottom: 12px;">' +
                '<div style="width: 36px; height: 36px; border-radius: 50%; background: ' + esc(rev.avatarBg || "#e0f2fe") + '; color: ' + esc(rev.avatarColor || "#0369a1") + '; display: flex; align-items: center; justify-content: center; font-weight: bold; font-size: 13px; flex-shrink: 0;">' + esc(rev.initials || "CL") + '</div>' +
                '<div style="text-align: left;">' +
                  '<h4 style="font-size: 13px; font-weight: 700; margin: 0; color: #0f172a;">' + esc(rev.author || "Cliente") + '</h4>' +
                  '<div style="display: flex; align-items: center; gap: 4px; margin-top: 2px;">' +
                    '<span style="' + badgeStyle + '">' + esc(rev.badge || "Cliente") + '</span>' +
                    '<span style="font-size: 8px; color: #475569;">• ' + esc(rev.date || "") + '</span>' +
                  '</div>' +
                '</div>' +
              '</div>' +
              '<div style="display: flex; gap: 2px; color: #f59e0b; margin-bottom: 10px;">' + starsHtml + '</div>' +
              '<p style="font-size: 13px; color: #334155; line-height: 1.5; margin: 0; font-style: italic; text-align: left;">"' + esc((rev.text || "").replace(/^"|"$/g, "")) + '"</p>' +
            '</div>' +
            '<div style="display: flex; align-items: center; justify-content: space-between; font-size: 10px; color: #475569; margin-top: 16px; border-top: 1px solid #e2e8f0; padding-top: 12px;">' +
              '<span style="display: flex; align-items: center; gap: 4px;">Google Maps</span>' +
              '<span style="color: #10b981; font-weight: 600;">✓ Verificada</span>' +
            '</div>' +
          '</div>';
        }).join("");

        if (dotsWrap) {
          dotsWrap.innerHTML = cfg.reviewsSection.items.map(function(_, idx) {
            var bg = idx === 0 ? "#0ea5e9" : "#e2e8f0";
            var op = idx === 0 ? "1" : "0.5";
            return '<button class="google-review-dot" style="width: 8px; height: 8px; border-radius: 50%; border: none; padding: 0; background: ' + bg + '; opacity: ' + op + '; cursor: pointer;" aria-label="Slide ' + (idx + 1) + '"></button>';
          }).join("");
        }
      }
    }
  }
}

if (typeof window !== "undefined") {
  window.NISSA_SITE_CONFIG = NISSA_SITE_CONFIG;
  window.applyNissaSiteConfig = applyNissaSiteConfig;
  if (document.readyState !== "loading") {
    applyNissaSiteConfig();
  } else {
    document.addEventListener("DOMContentLoaded", applyNissaSiteConfig);
  }
}
